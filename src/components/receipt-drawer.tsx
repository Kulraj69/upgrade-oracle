"use client";

// Native modal focus trapping, scroll locking and paper structure adapted from qloo.
import { useEffect, useRef } from "react";
import { ArrowUpRight, Check, ReceiptText, X } from "lucide-react";
import type { Finding } from "@/lib/types";

export function ReceiptDrawer({
  finding,
  recorded,
  onClose,
}: {
  finding: Finding | null;
  recorded: boolean;
  onClose: () => void;
}) {
  const dialog = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const node = dialog.current;
    if (finding && node && !node.open) {
      node.showModal();
      const oldOverflow = document.body.style.overflow;
      document.body.style.overflow = "hidden";
      return () => {
        document.body.style.overflow = oldOverflow;
        node.close();
      };
    }
  }, [finding]);
  return (
    <dialog
      ref={dialog}
      className="receipt-drawer"
      aria-labelledby="receipt-title"
      onCancel={onClose}
      onClick={(event) => {
        if (event.target === event.currentTarget) onClose();
      }}
    >
      {finding && (
        <div className="receipt-paper">
          <div className="drawer-top">
            <span>
              <ReceiptText size={16} /> EVIDENCE RECEIPT
            </span>
            <button
              type="button"
              className="icon-button"
              aria-label="Close receipt"
              onClick={onClose}
              autoFocus
            >
              <X size={22} />
            </button>
          </div>
          <div className="receipt-brand">
            UPGRADE
            <br />
            ORACLE<span>5150 / SOFTWARE DIVISION</span>
          </div>
          <div className="receipt-rule" />
          <h2 id="receipt-title">{finding.api}</h2>
          <p>
            {finding.dependency} / {finding.from} → {finding.to}
          </p>
          <span className="receipt-stamp">
            <Check size={15} /> VERBATIM QUOTE VERIFIED
          </span>
          <section>
            <span className="receipt-label">01 / THE SOURCE</span>
            <p>Release {finding.sourceVersion}</p>
            <a href={finding.receipt.url} target="_blank" rel="noreferrer">
              Open original release note <ArrowUpRight size={14} />
            </a>
            <small className="receipt-url">{finding.receipt.url}</small>
          </section>
          <section>
            <span className="receipt-label">02 / THE EXACT WORDS</span>
            <blockquote>{finding.receipt.quote}</blockquote>
            <small>
              This text passed an exact substring check against the fetched
              release note. The interpretation below is generated by GLM.
            </small>
          </section>
          <section>
            <span className="receipt-label">03 / THE INTERPRETATION</span>
            <p>{finding.change}</p>
            <span className="receipt-label">MIGRATION GUIDANCE</span>
            <p>{finding.migration}</p>
          </section>
          <section>
            <span className="receipt-label">04 / YOUR CODE</span>
            {finding.hits.length ? (
              finding.hits.map((hit, index) => (
                <div
                  className="receipt-hit"
                  key={`${hit.file}-${hit.line}-${index}`}
                >
                  <strong>
                    {hit.file}:{hit.line}
                  </strong>
                  <small>{hit.match} lexical match</small>
                  <pre>{hit.snippet}</pre>
                </div>
              ))
            ) : (
              <p>
                No matching token in the supplied files. This is not a
                whole-project safety guarantee.
              </p>
            )}
          </section>
          <div className="receipt-rule" />
          <p className="receipt-note">
            {recorded
              ? "RECORDED LIVE RUN / Replayed without new model calls."
              : "LIVE RUN / Generated from fetched public sources."}
            <br />A matched API is a review signal, not a runtime proof.
          </p>
          <div className="barcode" aria-hidden="true" />
          <div className="receipt-end">
            NO CLAIM WITHOUT A RECEIPT.
            <br />* * * END OF TRANSMISSION * * *
          </div>
        </div>
      )}
    </dialog>
  );
}
